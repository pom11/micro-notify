"""Shared test harness (design section 7).

Later build steps add fixtures in their own test modules — do not edit this file.
The one exception so far is the P0 hermeticity guard (card t_ffb69576, 2026-10-31),
which had to live here to be global; its two autouse fixtures are load-bearing and
must not be weakened or removed. It provides:

* ``no_network`` (autouse): every test runs with ``socket.socket.connect``,
  ``socket.create_connection``, ``socket.create_server``,
  ``socket.getaddrinfo`` and ``socket.gethostbyname`` patched to raise. No test
  can open a real connection or resolve a real name (design §7: "a test that
  FAILS if any test performs a real network call").
* ``test_socket_block_harness_works``: proves the harness itself bites, so it
  cannot rot silently. Run it directly:
  ``pytest -q tests/conftest.py::test_socket_block_harness_works``.
* ``mnotify_config(tmp_path)``: a valid placeholder config written to tmp_path,
  ``MICRO_NOTIFY_CONFIG`` pointed at it, and ``[paths]`` redirected so the audit
  log and counter never touch the real HOME. Its ``[allow]`` is populated
  (example.com / contoso.com placeholders) so send-path tests reach the transport;
  guard tests that need the refuse-everything default build their own file with
  ``write_config`` + a modified ``placeholder_config``.
* ``fake_keychain``: in-memory stand-in for :mod:`micro_notify.secrets`. It
  installs itself as the process-wide runner, so a command module that calls
  ``secrets.get(...)`` goes to the fake and never to ``/usr/bin/security``.
* ``hermetic_home`` (autouse): the P0 guard. Every test runs with ``HOME`` pinned
  under ``tmp_path`` and ``MICRO_NOTIFY_CONFIG`` pointed at a file under
  ``tmp_path``, so the default config path resolves inside the test's own tree,
  and with the real ``~/.config/mnotify`` watched: anything created, modified or
  deleted there during a test fails that test. It also fails any test that asks
  the real subprocess layer for ``security(1)`` — the keychain binary. See
  ``tests/test_hermeticity.py`` for the proofs that this guard bites.
"""

