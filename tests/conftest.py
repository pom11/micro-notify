def _blocked(*_args: object, **_kwargs: object):
    raise RuntimeError("network access blocked in tests")


# --- Socket blocking (autouse) ---------------------------------------------
# Names patched at module import so a typo fails loudly here rather than
# silently leaving a hole in the harness.
_PATCHED_SOCKET_NAMES = (
    "socket.socket.connect",
    "socket.socket.connect_ex",
    "socket.create_connection",
    "socket.create_server",
    "socket.getaddrinfo",
    "socket.gethostbyname",
    "socket.gethostbyname_ex",
)


@pytest.fixture(autouse=True)
def no_network(monkeypatch: pytest.MonkeyPatch) -> None:
    """Block every outbound path for the duration of a test (design §7)."""
    monkeypatch.setattr(socket.socket, "connect", _blocked, raising=True)
    monkeypatch.setattr(socket.socket, "connect_ex", _blocked, raising=True)
    monkeypatch.setattr(socket, "create_connection", _blocked, raising=True)
    monkeypatch.setattr(socket, "create_server", _blocked, raising=True)
    monkeypatch.setattr(socket, "getaddrinfo", _blocked, raising=True)
    monkeypatch.setattr(socket, "gethostbyname", _blocked, raising=True)
    monkeypatch.setattr(socket, "gethostbyname_ex", _blocked, raising=True)


def test_socket_block_harness_works() -> None:
    """The harness bites: a real HTTPS request must be blocked, not skipped."""
    import httpx

    with pytest.raises(RuntimeError, match="network access blocked in tests"):
        httpx.get("https://example.com", timeout=2.0)


def test_socket_block_harness_covers_resolution() -> None:
    """Name resolution is blocked too — a transport that resolves first is caught."""
    with pytest.raises(RuntimeError, match="network access blocked in tests"):
        socket.getaddrinfo("example.com", 443)


