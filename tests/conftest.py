def read_json_lines(tmp_path: Path):
    """Return a callable reading a JSONL file into a list of dicts."""

    def _read(path: Path) -> list[dict]:
        if not path.exists():
            return []
        return [json.loads(line) for line in path.read_text(encoding="utf-8").splitlines() if line.strip()]

    return _read


